"use client";

import useSWR from 'swr';
import { Sparkles } from 'lucide-react';
import { motion } from 'framer-motion';

const fetcher = (url: string) => fetch(url).then(res => res.json());

interface BriefResponse {
  brief_markdown: string;
}

export function AIBrief({ hospitalId }: { hospitalId: string }) {
  const { data, error, isLoading } = useSWR<BriefResponse>(
    `/api/v1/brief/hospital/${hospitalId}`,
    fetcher
  );

  // Simple Markdown Renderer for the demo
  const renderMarkdown = (text: string) => {
    return text.split('\n').map((line, i) => {
      if (!line.trim()) return null;
      if (line.startsWith('# ')) return <h3 key={i} className="text-lg font-bold text-gray-900 mb-4">{line.replace('# ', '')}</h3>;
      
      const parts = line.split(/(\*\*.*?\*\*)/g);
      return (
        <p key={i} className="mb-3 text-sm text-gray-700 leading-relaxed">
          {parts.map((part, j) => {
            if (part.startsWith('**') && part.endsWith('**')) {
              return <strong key={j} className="font-semibold text-[#111111]">{part.slice(2, -2)}</strong>;
            }
            return part;
          })}
        </p>
      );
    });
  };

  return (
    <div className="bg-gradient-to-br from-[#111111] to-[#2a2a2a] p-[1px] rounded-2xl h-full">
      <div className="bg-white rounded-[15px] p-6 h-full flex flex-col">
        <div className="flex items-center gap-2 mb-6 text-[#111111]">
          <Sparkles size={20} className="text-[#111111]" />
          <h2 className="text-lg font-bold tracking-tight">AI Executive Brief</h2>
        </div>

        {isLoading ? (
          <div className="flex-1 space-y-4 animate-pulse">
            <div className="h-6 w-3/4 bg-gray-100 rounded"></div>
            <div className="h-4 w-full bg-gray-100 rounded"></div>
            <div className="h-4 w-5/6 bg-gray-100 rounded"></div>
            <div className="h-4 w-full bg-gray-100 rounded"></div>
          </div>
        ) : error || !data ? (
          <div className="flex-1 flex items-center justify-center text-sm text-gray-400">
            Unable to generate brief.
          </div>
        ) : (
          <motion.div 
            initial={{ opacity: 0 }}
            animate={{ opacity: 1 }}
            className="flex-1"
          >
            {renderMarkdown(data.brief_markdown)}
          </motion.div>
        )}
        
        <div className="mt-6 pt-4 border-t border-gray-100 text-xs text-gray-400 flex justify-between items-center">
          <span>Generated by Pharmasense-LLM</span>
          <button className="text-[#111111] font-medium hover:underline">Regenerate</button>
        </div>
      </div>
    </div>
  );
}
